"""Generate audited stdcall boundaries and retain original bodies for comparison."""
from pathlib import Path
import capstone
import hashlib
import json
import re

root=Path(__file__).resolve().parents[1]
selected={
    'Direct3D_CreateDevice':6,'D3DDevice_GetGammaRamp':1,
    'D3DDevice_SetBackBufferScale':2,'D3DDevice_Clear':6,'D3DDevice_Swap':1,
    'D3DDevice_SetFlickerFilter':1,'D3DDevice_SetSoftDisplayFilter':1,
    'D3DDevice_GetBackBuffer2':1,'D3DSurface_GetDesc':2,
    'D3DDevice_GetDepthStencilSurface2':0,'D3DDevice_SetRenderTarget':2,
    'D3DResource_AddRef':1,'D3DResource_Release':1,'D3DDevice_FlushVertexCache':0,
    'D3DDevice_DrawIndexedVertices':3
}
data=(root/'input/default.xbe').read_bytes()
assert hashlib.sha256(data).hexdigest()=='438eaeada465b3b560a7578436504274525e904534a62753ea1e16be87ed6c83'
metadata={int(f['start'],16):f for f in json.loads((root/'analysis/ghidra-functions.json').read_text())}
xbe=json.loads((root/'analysis/xbe.json').read_text())
signatures=json.loads((root/'analysis/xdk-candidates.json').read_text())['candidates']
functions=[]
for name,argc in selected.items():
    matches=[c for c in signatures if c['name']==name]
    assert len(matches)==1
    c=matches[0]; address=int(c['address'],16); f=metadata[address]
    assert c['calling_convention']=='stdcall' and c['parameters'].count('psh ')==argc
    section=next(s for s in xbe['sections'] if int(s['virtual_addr'],16)<=address<int(s['virtual_addr'],16)+s['raw_size'])
    offset=int(section['raw_addr'],16)+address-int(section['virtual_addr'],16)
    code=data[offset:offset+int(f['end'],16)-address]
    ins=list(capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_32).disasm(code,address))
    returns=[i for i in ins if i.mnemonic=='ret']
    assert returns and all(int(i.op_str or '0',0)==argc*4 for i in returns), name
    functions.append({'name':name,'address':c['address'],'argc':argc,
        'status':'platform-specific native draw' if name=='D3DDevice_DrawIndexedVertices' else 'native startup implementation',
        'platforms':{'windows':'diagnostic hard stop','android':'native first splash verified'} if name=='D3DDevice_DrawIndexedVertices' else {'windows':'implemented','android':'implemented'},
        'sha256':hashlib.sha256(code).hexdigest(),'return_instructions':[hex(i.address) for i in returns]})

header=['/* Audited NHL 07 native graphics entry points. Generated by tools/apply_graphics_hooks.py. */',
        '#pragma once','#include <stdint.h>','typedef enum NhlGraphicsApi {']
header += ['    NHL_GFX_'+f['name']+',' for f in functions]
header += ['} NhlGraphicsApi;','uint32_t nhl07_graphics_call(NhlGraphicsApi api,const uint32_t *args);']
(root/'src/native_graphics.h').write_text('\n'.join(header)+'\n')
hooks=['/* Stack cleanup independently checked against every original RET. */',
       '#include "recomp_types.h"','#include "native_graphics.h"',
       '#include <stdio.h>','#include <stdlib.h>',
       'extern void sub_0076BD40(void);']
# Preserve the original pre-draw dirty-state preparation (thiscall, ret 4).
# It emits shader/texture/vertex-array methods into the guest push buffer.
address=0x76bd40; f=metadata[address]
section=next(s for s in xbe['sections'] if int(s['virtual_addr'],16)<=address<int(s['virtual_addr'],16)+s['raw_size'])
offset=int(section['raw_addr'],16)+address-int(section['virtual_addr'],16)
code=data[offset:offset+int(f['end'],16)-address]
returns=[i for i in capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_32).disasm(code,address) if i.mnemonic=='ret']
assert returns and all(int(i.op_str or '0',0)==4 for i in returns)
(root/'analysis/native-draw-prepare-abi.json').write_text(json.dumps({'address':hex(address),'sha256':hashlib.sha256(code).hexdigest(),
    'calling_convention':'thiscall; ECX=device, stack=base vertex; RET 4',
    'original_call_site':'0x764038','return_instructions':[hex(i.address) for i in returns]},indent=2))
for f in functions:
    address=int(f['address'],16); argc=f['argc']
    hooks += [f'void sub_{address:08X}(void) {{',f'    uint32_t args[{max(argc,1)}]={{0}};']
    hooks += [f'    args[{i}]=MEM32(g_esp+{4+i*4});' for i in range(argc)]
    if f['name']=='D3DDevice_DrawIndexedVertices':
        hooks += ['    uint32_t saved_sp=g_esp,device=MEM32(0x785178);',
            '    g_ecx=device; PUSH32(g_esp,MEM32(device+0x1c)); PUSH32(g_esp,0x76403d);',
            '    RECOMP_ABI_CALL(0x76bd40u,sub_0076BD40);',
            '    if(g_esp!=saved_sp) {fprintf(stderr,"[NHL07-ABI] draw prepare stack mismatch\\n");abort();}',
            '    MEM32(device+8)|=0x800;']
    hooks += [f'    g_eax=nhl07_graphics_call(NHL_GFX_{f["name"]},args);',f'    g_esp+={4+argc*4};','}']
(root/'src/native_graphics_hooks.c').write_text('\n'.join(hooks)+'\n')
for path in (root/'src/recomp/gen').glob('recomp_*.c'):
    source=path.read_text(); modified=source
    for f in functions:
        symbol='sub_'+f['address'][2:]
        modified=modified.replace('void '+symbol+'(void)\n{','void '+symbol+'_original_xbox(void)\n{')
    if modified!=source: path.write_text(modified,encoding='utf-8')
(root/'analysis/native-graphics-entries.json').write_text(json.dumps([f['address'] for f in functions],indent=2))
(root/'analysis/native-graphics-abi.json').write_text(json.dumps(functions,indent=2))
print('Audited graphics boundaries:',len(functions))
